"""Node inventory + connection tables of the reconstruction's node groups, read from the built trees (so the documents
cannot drift from the code). Blender, any file with the groups (factory startup builds them; MRS_Road's tongue frame
needs a file with MRS_Road, e.g. the road tongue test's):
    blender --background [file.blend] --factory-startup --python tools/roads/crm_reconstruction/build/graph_dump.py -- <out.md> [--road]"""
import bpy, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(HERE))))
sys.path.insert(0, os.path.join(ROOT, "tools", "roads"))
argv = sys.argv[sys.argv.index("--") + 1:]
OUT = os.path.abspath(argv[0])
from mrs import areajunction as AJ, customsign as CS, markinglines as ML
if "MRS_AreaJunction" not in bpy.data.node_groups: AJ.build_all()
if "MRS_CustomSign" not in bpy.data.node_groups: CS.build_custom_sign()
if "MRS_MarkingLines" not in bpy.data.node_groups: ML.build_marking_lines()
GROUPS = ["MRS_AreaJunction", "MRS_RegionOutline", "MRS_ExtensionMesh", "MRS_ExtensionCurve", "MRS_CustomSign", "MRS_PanelText", "MRS_MarkingLines"]


def val(s):
    if not hasattr(s, "default_value") or s.is_linked: return ""
    v = s.default_value
    try:
        if hasattr(v, "__len__") and not isinstance(v, str): v = "(" + ", ".join("%.3g" % x for x in v) + ")"
        elif isinstance(v, float): v = "%.4g" % v
        elif hasattr(v, "name"): v = v.name
    except Exception: v = str(v)
    return str(v)


def node_settings(n):
    out = []
    for p in ("operation", "data_type", "domain", "mode", "solver", "transform_space", "input_type"):
        if hasattr(n, p):
            try: out.append("%s=%s" % (p, getattr(n, p)))
            except Exception: pass
    for s in n.inputs:
        if s.enabled and not s.is_linked and s.type in ("VALUE", "INT", "BOOLEAN", "VECTOR", "STRING", "MENU", "ROTATION") and not s.hide_value:
            v = val(s)
            if v not in ("", "0", "0.0", "False", "(0, 0, 0)"): out.append("%s=%s" % (s.name, v))
    if n.bl_idname == "GeometryNodeGroup" and n.node_tree: out.insert(0, "group=%s" % n.node_tree.name)
    return "; ".join(out)


def frame_of(n):
    f = n.parent
    return f.label if f else ""


def dump(g, only_frame=None, title=None):
    lines = ["## %s" % (title or g.name), ""]
    nodes = [n for n in g.nodes if n.type != "FRAME" and (only_frame is None or (n.parent and only_frame in n.parent.label))]
    keep = set(n.name for n in nodes)
    if only_frame is None:
        lines += ["Interface:", "", "| socket | in/out | type | default | min | max | panel | description |", "|---|---|---|---|---|---|---|---|"]
        for it in g.interface.items_tree:
            if it.item_type != "SOCKET": continue
            d = getattr(it, "default_value", "")
            if hasattr(d, "name"): d = d.name
            elif isinstance(d, float): d = "%.4g" % d
            elif hasattr(d, "__len__") and not isinstance(d, str): d = "(" + ", ".join("%.3g" % x for x in d) + ")"
            lines.append("| %s | %s | %s | %s | %s | %s | %s | %s |" % (it.name, it.in_out.lower(), it.socket_type.replace("NodeSocket", ""), d,
                                                                        getattr(it, "min_value", ""), getattr(it, "max_value", ""),
                                                                        it.parent.name if it.parent and it.parent.name else "", (it.description or "").replace("|", "/")))
        lines.append("")
    lines += ["Nodes (%d):" % len(nodes), "", "| node | type | frame | settings |", "|---|---|---|---|"]
    for n in sorted(nodes, key=lambda n: (frame_of(n), n.location.y * -1, n.location.x)):
        lines.append("| %s | %s | %s | %s |" % (n.name, n.bl_idname, frame_of(n), node_settings(n).replace("|", "/")))
    lines += ["", "Connections:", "", "| source node | output socket | destination node | input socket |", "|---|---|---|---|"]
    for l in g.links:
        if only_frame is not None and not (l.from_node.name in keep or l.to_node.name in keep): continue
        lines.append("| %s | %s | %s | %s |" % (l.from_node.name, l.from_socket.name, l.to_node.name, l.to_socket.name))
    lines.append("")
    return lines

out = ["# Reconstruction node groups (generated)", "",
       "Generated by `build/graph_dump.py` from the built trees (Blender %s). Class C (implementation): these are our groups, not CRM's." % bpy.app.version_string, ""]
for name in GROUPS: out += dump(bpy.data.node_groups[name])
if "--road" in argv and "MRS_Road" in bpy.data.node_groups:
    out += dump(bpy.data.node_groups["MRS_Road"], only_frame="Tongues", title="MRS_Road: the Tongues frame (added for the area junction workflow)")
with open(OUT, "w", encoding="utf-8") as f: f.write("\n".join(out))
print("GRAPH_DUMP %s: %s" % (OUT, ", ".join("%s %d nodes" % (n, len(bpy.data.node_groups[n].nodes)) for n in GROUPS)))
