"""Sweep results -> the tool's limits (tools/roads/mrs/limits.json) and the evidence document (docs/roads/LIMITS.md).
    python -I tools/roads/limits/report.py <limits out_dir> [--apply]
Reads road_summary.json (or the road_summary_part<k>of<n>.json parts), area_summary.json and terrain_summary.json.
Without --apply only LIMITS.md is written (review first); with it, limits.json too (the next library build applies
the ranges as socket min / max; validate.check_limits reports values outside them and inside a forbidden gap)."""
import glob, json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
OUT = os.path.abspath(sys.argv[1]); APPLY = "--apply" in sys.argv


def load(name):
    p = os.path.join(OUT, name)
    return json.load(open(p)) if os.path.exists(p) else {}


road = load("road_summary.json")
if not road:
    for p in sorted(glob.glob(os.path.join(OUT, "road_summary_part*of*.json"))): road.update(json.load(open(p)))
area = load("area_summary.json"); terrain = load("terrain_summary.json")
fmt = lambda v: "-" if v is None else ("%g" % v if isinstance(v, (int, float)) else str(v))
lines = ["# Tested parameter limits", "",
         "Generated by `tools/roads/limits/report.py` from the limit sweeps (`tools/roads/limits`). Method: every value of a",
         "parameter's declared range on a dense grid (21 values, plus a log-spaced grid for wide ranges); for MRS_Road in six",
         "road shapes (straight, 60 m and 20 m radius curves, a 7 % grade, an S-bend, a fully painted banked curve; every",
         "roadside feature on); a value passes only when every check passes in every shape (eval, flipped, degenerate, fold,",
         "width, paint, validate, props: `tools/roads/limits/checks.py`; area junction, sign, line and terrain checks: the",
         "docstrings of `area_sweep.py` and `terrain_sweep.py`). Each pass / fail boundary is bisected to 1 % of its own value",
         "(at least 1 mm; integers to adjacent values) and the road boundaries are confirmed by five more values on the safe",
         "side. The limit is the refined boundary moved inward by 10 % of the boundary value (the user's choice; at least",
         "1 mm, whole steps for integers); a bound with no failure stays the declared one. A parameter can pass in several",
         "regions (0 = off, or at least a minimum width): the values between them are a forbidden gap, reported by the",
         "validator. Evidence per parameter: `tmp/roads/limits/{road,area,terrain}/<name>.json`.", ""]
limits = {}
# inputs whose sweep failures come from a combination with the test road, not from the value itself: no single limit,
# the named rule (a modifier warning + validate) covers them
COMBINATION = {("MRS_Road", "Taper Length"): "Transition Start + Taper Length must end on the road: the 'paint' scenario's 125 m road fails past "
                                              "113 m (MRS_Road warns, validate reports `warning`); the value itself has no limit",
               ("MRS_AreaJunction", "Distance"): "a Range radius shorter than the way to the nearest tongue builds nothing (the test's tongues start 4.5 m "
                                                 "out); validate reports `tongue_uncovered` for a tongue no junction reaches",
               ("MRS_Road", "Planting Strip Left"): "RESWEEP on v27: below 0.6 m the trees moved beyond the sidewalk edge and hung in the air with no terrain; "
                                                    "they now stand on the terrain or are left out (road.on_surface ground=True)",
               ("MRS_Road", "Planting Strip Right"): "RESWEEP on v27: as Planting Strip Left"}
# a sign's texts, images, lines and corner rounding must fit its panel, and a line's offset must fit its Road Size: how
# much depends on the other inputs (panel size and shape, text length, Road Size), so the groups warn (MRS_CustomSign:
# content off the panel; MRS_MarkingLines: a line outside Road Size / 2) instead of limiting one input
SIGN_CONTENT = lambda name: name.startswith(("L", "Line ", "Image ")) or name in ("Scale X", "Scale Y", "Bevel Radius")
def combination(group, name):
    if (group, name) in COMBINATION: return COMBINATION[(group, name)]
    if group == "MRS_CustomSign" and SIGN_CONTENT(name): return "content must fit the panel (depends on Scale X / Y, Shape and the texts): the sign warns when it does not"
    if group == "MRS_MarkingLines" and name in ("Center X", "Lane X"): return "a line lies within Road Size / 2 of the curve (depends on Road Size): the group warns when it does not"
    return None
SLIVER = 0.05              # a passing region narrower than this share of the declared range is noise between failures, not a region
HEAD = ["| input | type | default | declared | passing regions | allowed (with margin) | forbidden gaps | evaluations | status |",
        "|---|---|---|---|---|---|---|---|---|"]


def table(title, rows, evidence):
    global lines
    if not rows: return
    lines += ["## %s" % title, ""] + HEAD
    for (group, name), r in sorted(rows.items()):
        status = r.get("status") or ("ok" if r.get("default_passes", True) else "default fails")
        dec = "[%s, %s]" % tuple(map(fmt, r["declared"]))
        if status == "default fails":
            lines.append("| %s | %s | %s | %s | default fails | | | %s | **default fails** |" % (name, r.get("type"), fmt(r.get("default")), dec, r.get("n_evals")))
            continue
        span = float(r["declared"][1]) - float(r["declared"][0])
        allowed = [a for a in (r.get("allowed") or []) if a[1] - a[0] >= SLIVER * span or len(r.get("allowed") or []) == 1]
        if allowed and len(allowed) < len(r.get("allowed") or []):          # slivers dropped: the limit and the gaps follow
            r = dict(r, allowed=allowed, limit=[min(a[0] for a in allowed), max(a[1] for a in allowed)],
                     gaps=[[allowed[k][1], allowed[k + 1][0]] for k in range(len(allowed) - 1)])
        lim = r.get("limit") or [None, None]
        rg = " ".join("[%s, %s]" % (fmt(x[0]), fmt(x[1])) for x in r.get("regions", []) or [])
        al = " ".join("[%s, %s]" % (fmt(x[0]), fmt(x[1])) for x in r.get("allowed", []) or [])
        gp = " ".join("(%s, %s)" % (fmt(x[0]), fmt(x[1])) for x in r.get("gaps", []) or []) or "-"
        comb = combination(group, name)
        if comb and (list(lim) != list(r["declared"]) or r.get("gaps")):
            status = "combination rule"; lines.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s: %s |" % (name, r.get("type"), fmt(r.get("default")), dec, rg, al, gp, r.get("n_evals"), status, comb))
            continue
        lines.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (name, r.get("type"), fmt(r.get("default")), dec, rg, al, gp, r.get("n_evals"), status))
        if status == "ok" and lim[0] is not None and (list(lim) != list(r["declared"]) or r.get("gaps")):
            limits.setdefault(group, {})[name] = {"min": lim[0], "max": lim[1], "gaps": r.get("gaps", []), "regions_passing": r.get("regions"),
                                                  "declared": r["declared"], "evidence": evidence % (group, name.replace(" ", "_"))}
    lines.append("")


table("MRS_Road", {("MRS_Road", k): v for k, v in road.items()}, "tmp/roads/limits/road/%.0s%s.json")
by_group = {}
for k, v in area.items():
    g, n = k.split("/", 1); by_group.setdefault(g, {})[(g, n)] = v
for g in sorted(by_group): table(g, by_group[g], "tmp/roads/limits/area/%s_%s.json")
table("MRS_TerrainConform", {tuple(k.split("/", 1)): v for k, v in terrain.items()}, "tmp/roads/limits/terrain/%.0s%s.json")
bend = load("bend_sweep.json")
if bend.get("rule_ratio"):
    limits.setdefault("_rules", {}).setdefault("MRS_Road", {})["bend_ratio"] = bend["rule_ratio"]
    lines += ["## Bend radius against road width (combination rule)", "",
              "The tightest bend a road takes before its inner side folds, per profile (`bend_sweep.py`: a 120 degree arc between",
              "straights, the radius bisected to 1 %%, five larger radii confirmed). H = the road's outer half width (carriageway +",
              "kerb + sidewalk, the wider side). Rule: **R >= %g x H** (the worst R_fail / H of %g, + 10 %%); MRS_Road warns on the" % (bend["rule_ratio"], bend["ratio_max"]),
              "modifier and validate reports `warning` when a bend is tighter.", "",
              "| profile | H (m) | R_fail (m) | R_fail / H | confirmed |", "|---|---|---|---|---|"]
    for pr in bend.get("profiles", []):
        lines.append("| %s | %s | %s | %s | %s |" % (pr["profile"], fmt(pr.get("H")), fmt(pr.get("R_fail")), fmt(pr.get("ratio")),
                                                   "yes" if pr.get("ratio") is not None and not pr.get("confirm_failures") else (pr.get("error") or pr.get("note") or "CHECK")))
    lines.append("")
for fn, title in (("junction_v22.json", "Junction approach angle"), ("junction_length_v22.json", "Road length between junctions")):
    p = os.path.join(OUT, fn)
    if not os.path.exists(p): continue
    d = json.load(open(p))
    lines += ["## %s" % title, "", "| case | result |", "|---|---|"]
    for k, v in d["summary"].items(): lines.append("| %s | %s |" % (k, json.dumps(v)[:300].replace("|", "/")))
    lines.append("")
lines += ["Rules derived from these sweeps (not single-input limits):",
          "- Junction approach angle: no geometric failure was found above the angle where a 70 m road is trimmed away;",
          "  junction.MIN_APPROACH_ANGLE keeps its 25 degree refusal for 3+ arms.",
          "- A road keeps both ends' paint zones x (1 + junction.ZONE_MARGIN) between its trims: build_junction refuses",
          "  otherwise, validate reports junction_zones, citynet merges such junctions."]
doc = os.path.join(ROOT, "docs", "roads", "LIMITS.md")
with open(doc, "w", encoding="utf-8") as f: f.write("\n".join(lines) + "\n")
print("LIMITS.md: %d road, %d area, %d terrain inputs; tested limits: %s" % (len(road), len(area), len(terrain), {g: len(v) for g, v in limits.items()}))
if APPLY:
    path = os.path.join(ROOT, "tools", "roads", "mrs", "limits.json")
    with open(path, "w", encoding="utf-8") as f: json.dump(limits, f, indent=1)
    print("applied ->", path)
