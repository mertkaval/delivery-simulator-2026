"""Sweep results -> the tool's limits (tools/roads/mrs/limits.json) and the evidence document (docs/roads/LIMITS.md).
    python -I tools/roads/limits/report.py <limits out_dir> [--apply]
Without --apply only LIMITS.md is written (review first); with it, limits.json too (the next library build applies
the ranges as socket min / max; validate.check_limits reports values outside them)."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
OUT = os.path.abspath(sys.argv[1]); APPLY = "--apply" in sys.argv
road = json.load(open(os.path.join(OUT, "road_summary.json"))) if os.path.exists(os.path.join(OUT, "road_summary.json")) else {}
lines = ["# Tested parameter limits", "",
         "Generated by `tools/roads/limits/report.py` from the limit sweeps (`tools/roads/limits`). Method: every value of a",
         "parameter's declared range on a dense grid (21 values, plus a log-spaced grid for wide ranges) in five road shapes",
         "(straight, 60 m and 20 m radius curves, a 7 % grade, an S-bend; every roadside feature on); a value passes only when",
         "every check passes in every shape (eval, flipped, degenerate, fold, width, paint, validate, props: see",
         "`tools/roads/limits/checks.py`). Each pass / fail boundary is bisected to 1 % of the range and confirmed by five more",
         "values on the safe side. The limit is the refined boundary moved inward by 10 % of the safe interval (the user's",
         "choice); a bound with no failure stays the declared one. Evidence per parameter: `tmp/roads/limits/road/<name>.json`.", "",
         "## MRS_Road", "", "| input | type | default | declared | passes | first failure below / above | limit | evaluations | status |",
         "|---|---|---|---|---|---|---|---|---|"]
limits = {"MRS_Road": {}}
fmt = lambda v: "-" if v is None else ("%g" % v if isinstance(v, (int, float)) else str(v))
for name, r in sorted(road.items()):
    if r.get("status") == "default fails":
        lines.append("| %s | %s | %s | %s | default fails | | | %s | **default fails** |" % (name, r["type"], fmt(r["default"]), "[%s, %s]" % tuple(map(fmt, r["declared"])), r.get("n_evals")))
        continue
    pi = r.get("pass_interval") or [None, None]; lim = r.get("limit") or [None, None]
    lines.append("| %s | %s | %s | [%s, %s] | [%s, %s] | %s / %s | [%s, %s] | %s | %s |" % (
        name, r["type"], fmt(r["default"]), fmt(r["declared"][0]), fmt(r["declared"][1]), fmt(pi[0]), fmt(pi[1]),
        fmt(r.get("first_fail_below")), fmt(r.get("first_fail_above")), fmt(lim[0]), fmt(lim[1]), r.get("n_evals"), r.get("status")))
    if r.get("status") == "ok" and (r.get("first_fail_below") is not None or r.get("first_fail_above") is not None):
        limits["MRS_Road"][name] = {"min": lim[0], "max": lim[1], "declared": r["declared"], "first_fail_below": r.get("first_fail_below"),
                                    "first_fail_above": r.get("first_fail_above"), "evidence": "tmp/roads/limits/road/%s.json" % name.replace(" ", "_")}
for fn, title in (("junction_v22.json", "Junction approach angle"), ("junction_length_v22.json", "Road length between junctions")):
    p = os.path.join(OUT, fn)
    if not os.path.exists(p): continue
    d = json.load(open(p))
    lines += ["", "## %s" % title, "", "| case | result |", "|---|---|"]
    for k, v in d["summary"].items(): lines.append("| %s | %s |" % (k, json.dumps(v)[:300].replace("|", "/")))
lines += ["", "Rules derived from these sweeps (not single-input limits):",
          "- Junction approach angle: no geometric failure was found above the angle where a 70 m road is trimmed away;",
          "  junction.MIN_APPROACH_ANGLE keeps its 25 degree refusal for 3+ arms.",
          "- A road keeps both ends' paint zones x (1 + junction.ZONE_MARGIN) between its trims: build_junction refuses",
          "  otherwise, validate reports junction_zones, citynet merges such junctions."]
doc = os.path.join(ROOT, "docs", "roads", "LIMITS.md")
with open(doc, "w", encoding="utf-8") as f: f.write("\n".join(lines) + "\n")
print("LIMITS.md: %d road inputs, %d with a tested limit" % (len(road), len(limits["MRS_Road"])))
if APPLY:
    path = os.path.join(ROOT, "tools", "roads", "mrs", "limits.json")
    with open(path, "w", encoding="utf-8") as f: json.dump(limits, f, indent=1)
    print("applied ->", path)
