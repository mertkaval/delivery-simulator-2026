def save(name,collision=None):
    groups=defaultdict(list)
    for o in list(bpy.context.scene.objects):
        if o.type=='MESH':
            bm=bmesh.new(); bm.from_mesh(o.data); bmesh.ops.recalc_face_normals(bm,faces=list(bm.faces)); bm.to_mesh(o.data); bm.free()
            groups[o.data.materials[0].name].append(o)
    for material,objects in groups.items():
        bpy.ops.object.select_all(action='DESELECT')
        for o in objects: o.select_set(True)
        bpy.context.view_layer.objects.active=objects[0]
        if len(objects)>1: bpy.ops.object.join()
        o=bpy.context.object; o.name=material
        bpy.ops.object.transform_apply(location=True,rotation=True,scale=True)
        bpy.ops.object.mode_set(mode='EDIT'); bpy.ops.mesh.select_all(action='SELECT')
        bpy.ops.uv.smart_project(angle_limit=1.1519,island_margin=.02)
        bpy.ops.object.mode_set(mode='OBJECT')
    near=sum(sum(len(p.vertices)-2 for p in o.data.polygons) for o in bpy.context.scene.objects if o.type=='MESH')
    bpy.ops.wm.save_as_mainfile(filepath=os.path.join(OUT,'source',name+'.blend'))
    bpy.ops.export_scene.gltf(filepath=os.path.join(OUT,name+'.glb'),export_format='GLB',export_apply=True)
    for o in list(bpy.context.scene.objects):
        if o.type=='MESH' and len(o.data.polygons)>30:
            bpy.context.view_layer.objects.active=o
            dec=o.modifiers.new('Distance mesh simplification','DECIMATE'); dec.ratio=.32
            bpy.ops.object.modifier_apply(modifier=dec.name)
    far=sum(sum(len(p.vertices)-2 for p in o.data.polygons) for o in bpy.context.scene.objects if o.type=='MESH')
    bpy.ops.export_scene.gltf(filepath=os.path.join(OUT,name+'_far.glb'),export_format='GLB',export_apply=True)
    MANIFEST[name]={'triangles_near':near,'triangles_far':far,'materials':len(groups),'uv':'Smart UV, .02 margin','metres':True,'collision':collision}
    print('URBAN MODULE',name,near,far,flush=True)

